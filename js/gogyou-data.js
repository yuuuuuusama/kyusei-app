(function (global) {
  'use strict';

  const COLS = ['臓','腑','精','音','季','方','悪','根','主','支','役','色','香','味','声','液','志','果','菜','穀','畜','音色','音調'];

  const GOGYOU_DATA = {
    '木': ['肝','胆','魂','角','春','東','風','眼','筋','爪','色','青','臊','酸','呼','涙','怒','李','韮','麦','鶏','カ行','牙'],
    '火': ['心','小腸','神','徴','夏','南','熱','舌','血','毛','臭','赤','焦','苦','言','汗','笑','杏','薤','黍','羊','タナラ行','舌'],
    '土': ['脾','胃','意智','宮','土用','中央','湿','唇','肌肉','乳','味','黄','香','甘','歌','涎','思','棗','葵','粟','牛','アワヤ行','喉'],
    '金': ['肺','大腸','魄','商','秋','西','燥','鼻','皮膚','息','声','白','腥','辛','哭','涕','慮','桃','葱','稲','馬','サ行','歯'],
    '水': ['腎','膀胱','精志','羽','冬','北','寒','耳','骨','髪','液','黒','腐','鹹','呻','唾','恐','栗','藿','豆','豚','ハマ行','喉']
  };

  global.GogyouData = {
    cols: COLS,
    rows: GOGYOU_DATA,
    get: (element, col) => {
      const row = GOGYOU_DATA[element];
      if (!row) return null;
      const idx = COLS.indexOf(col);
      return idx >= 0 ? row[idx] : null;
    }
  };
})(typeof window !== 'undefined' ? window : globalThis);
